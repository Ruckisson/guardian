"""Single-file HTML report in the Graphite design, standard library only.

The page works offline: CSS is inline, charts are inline SVG, and there are
no scripts, web fonts or loaded resources (the only links are the sources in
the static "Why it matters" block). Every value that comes from the config,
a rule or the file name goes through ``_e`` (``html.escape``) before it
reaches the page. Templates are ``string.Template``, so a ``$`` or ``{`` in a
value is never interpreted.

The approved design lives in ``docs/design/report-graphite.html``; its CSS
is ``graphite.css`` and its static context block ``context.html``.
"""

